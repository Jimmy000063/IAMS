"""announcements and notifications

Revision ID: 0007
Revises: 0006
Created: 2026-10-15 18:05:42.284514


Announcements and notifications are separate tables, not one "message" table.
An announcement is a single company-wide artefact with an audience, a schedule
and a read report; a notification is one row per person about one fact. Merging
them would mean either duplicating a notice's text per recipient or losing the
per-person read state.

The guarantee this migration exists for is ``unique(dedupe_key)`` on
``notifications``. Every caller derives that key from the *fact* - the leave
application and its decision, the attendance date, the announcement and the
user - and never from the run id or the posting time. A retried scheduler run,
a re-published announcement or a re-processed attendance day therefore inserts
nothing the second time. Without the constraint, deduplication would depend on
every caller reading before writing, which two concurrent runs defeat.

Also enforced in the database rather than in the service:

* ``announcement_targets`` - ``(target_type = 'all') = (target_id IS NULL)``,
  so an "everyone" target cannot carry a stray id and a scoped target cannot
  be missing one. ``target_id`` is deliberately **not** a foreign key: it
  points at one of four tables depending on ``target_type``, and the service
  validates it against the right one on write.
* ``announcement_reads`` - one row per announcement and employee, with
  ``read_at`` immutable by trigger. When somebody read a notice is a fact; a
  later visit does not rewrite it. ``acknowledged_at`` is separate, because
  opening a critical notice is not the same as confirming it.
* ``notifications`` - the identity of a notification (who, what, which key,
  when it was created) is immutable by trigger. Only the recipient's own state
  (read, archived) and the delivery outcome may change.

Partial indexes carry the two hot queries: the unread badge
(``WHERE read_at IS NULL``) and the live feed (``WHERE status = 'published'``).
Both are small slices of tables that only grow, so indexing the whole of either
would cost far more to keep than it returns.

Delivery is in-app only. ``channel`` admits email, sms and push so an optional
adapter can be added later without a migration, but nothing here requires a
paid service to work.
"""

