"""payroll and statutory configuration

Revision ID: 0008
Revises: 0007


Nothing in these fourteen tables is seeded. No salary component, no rate, no
ceiling, no slab. The schema is built so that a statutory figure cannot be used
without a rule set that cites its source and has been explicitly verified:

* ``statutory_rule_sets`` carries ``source_reference``, ``verified_by_user_id``
  and ``verified_at``, and a check constraint refuses the ``verified`` status
  unless all three are present. A rate with no provenance therefore cannot be
  marked as checked.
* ``statutory_rule_parameters`` holds the individual rates, ceilings and slabs,
  with a check constraint allowing exactly one of ``numeric_value`` and
  ``json_value`` - so a rate cannot be stored as a string that happens to parse,
  and a slab table needs no second table of its own.
* ``unique(domain, jurisdiction, state_code, effective_from)`` means one set of
  rules is in force for a domain on any given date, which is what makes "which
  rules did March use" answerable.

What makes a past payroll reproducible, and therefore auditable:

* ``payroll_runs.rule_set_snapshot`` records the id and version of every rule
  set the run used, and ``settings_snapshot`` the payable-days basis and
  rounding mode in force. Changing either next month cannot retrospectively
  alter what was paid.
* ``payslip_lines`` stores ``basis_amount`` and ``basis_description`` beside
  every figure, and a statutory line cites its rule set. "PF 1800" cannot be
  checked by the person it was deducted from; "12% of a PF wage of 15000" can.
* ``payroll_runs.idempotency_key`` is unique over the period and run type, so
  two regular runs for one month are impossible.
* A finalized run is immutable, enforced by trigger. A correction is a
  ``payroll_adjustments`` row applied in a later run, because rewriting a
  finalized month would falsify the register the bank transfer and the statutory
  filings were made from.

Money is ``NUMERIC(14, 2)`` and day counts ``NUMERIC(6, 2)`` throughout. No
monetary value is a float anywhere in this system.
"""

