"""Regenerate the pinned requirement files from the current environment.

`pyproject.toml` declares which packages this project needs and the version
ranges it accepts. That is the source of truth, and it is what `pip install -e
".[dev]"` reads. The requirement files are something else: an exact record of
one working set of versions, so that a checkout on another machine installs
what this machine has rather than whatever the ranges resolve to that day.

Both exist on purpose. Editing either by hand defeats the point of having them,
so run this instead:

    python scripts/generate_requirements.py

from `backend/`, with the virtual environment active and in the state you want
recorded. Review the diff before keeping it: an unexpected version jump here is
exactly the kind of thing worth noticing.

The split between runtime and development is computed, not typed out. Each list
in `pyproject.toml` is walked through its installed metadata to collect the
packages it pulls in; anything reachable only from the development list lands in
the development file. Hand-maintaining that split is how a transitive dependency
ends up missing from production.
"""

from __future__ import annotations

import sys
import tomllib
from importlib.metadata import PackageNotFoundError, distribution, distributions
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

BACKEND = Path(__file__).resolve().parent.parent
PYPROJECT = BACKEND / "pyproject.toml"

HEADER = """\
# Generated by scripts/generate_requirements.py - do not edit by hand.
#
# Exact versions, recorded from a working environment, so that a fresh checkout
# installs what was tested rather than whatever the ranges in pyproject.toml
# resolve to today. pyproject.toml remains the place to add or remove a
# dependency; this file only pins one.
#
#     pip install -r requirements.txt
#
# Python {python}
"""

DEV_HEADER = """\
# Generated by scripts/generate_requirements.py - do not edit by hand.
#
# Everything in requirements.txt, plus the test and lint tooling.
#
#     pip install -r requirements-dev.txt
#
# Note that pytest-xdist is not optional despite living under the development
# extra: pytest's `addopts` passes `-n 4`, so the suite will not start without
# it.

-r requirements.txt

"""


def closure(specs: list[str]) -> set[str]:
    """Every installed package reachable from `specs`, following metadata.

    Extras are carried along the walk rather than discarded, because they
    change what a package depends on: `uvicorn[standard]` pulls in httptools,
    watchfiles, websockets and PyYAML, and `psycopg[binary]` pulls in the
    compiled driver. Dropping the extras silently loses all five, and the
    resulting requirement file installs a server that cannot reload and a
    database driver with no binary behind it.
    """
    visited: set[tuple[str, frozenset[str]]] = set()
    packages: set[str] = set()
    queue = [
        (canonicalize_name(requirement.name), frozenset(requirement.extras))
        for requirement in (Requirement(spec) for spec in specs)
    ]

    while queue:
        name, extras = queue.pop()
        if (name, extras) in visited:
            continue
        visited.add((name, extras))

        try:
            dist = distribution(name)
        except PackageNotFoundError:
            # Declared but not installed. Reported rather than guessed at: a
            # missing package means a broken environment, and writing a
            # requirement file from one would record the breakage.
            print(f"  not installed: {name}", file=sys.stderr)
            continue
        packages.add(name)

        for spec in dist.requires or []:
            requirement = Requirement(spec)
            marker = requirement.marker
            if marker is not None:
                # A requirement gated on `extra == "standard"` is followed only
                # when that extra was asked for. The empty string covers the
                # ordinary case of a marker that tests something else, such as
                # the Python version or the platform.
                environments = [{"extra": extra} for extra in sorted(extras)]
                environments.append({"extra": ""})
                if not any(marker.evaluate(environment) for environment in environments):
                    continue
            queue.append((canonicalize_name(requirement.name), frozenset(requirement.extras)))

    return packages


def main() -> int:
    data = tomllib.loads(PYPROJECT.read_text(encoding="utf-8"))
    project = data["project"]

    runtime = closure(project["dependencies"])
    development = closure(project["optional-dependencies"]["dev"]) - runtime

    installed = {
        canonicalize_name(dist.metadata["Name"]): dist.version
        for dist in distributions()
        if dist.metadata["Name"]
    }

    # Packaging machinery that every environment has and nothing declares.
    ignored = {"pip", "setuptools", "wheel", canonicalize_name(project["name"])}
    unclaimed = sorted(set(installed) - runtime - development - ignored)
    if unclaimed:
        print("installed but not required by anything declared:")
        for name in unclaimed:
            print(f"  {name}=={installed[name]}")
        print("(left out of both files - remove them, or declare them)")

    def render(names: set[str]) -> str:
        lines = []
        for name in sorted(names):
            version = installed.get(name)
            if version is None:
                continue
            lines.append(f"{name}=={version}")
        return "\n".join(lines) + "\n"

    python = f"{sys.version_info.major}.{sys.version_info.minor}"
    (BACKEND / "requirements.txt").write_text(
        HEADER.format(python=python) + "\n" + render(runtime), encoding="utf-8"
    )
    (BACKEND / "requirements-dev.txt").write_text(
        DEV_HEADER + render(development), encoding="utf-8"
    )

    print(f"requirements.txt: {len(runtime)} packages")
    print(f"requirements-dev.txt: {len(development)} packages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
