"""Announcements and the in-app notification centre.

Two distinct things
-------------------
An **announcement** is something HR publishes for people to read: a policy
change, an office closure. It is targeted at groups, scheduled, and the same
content for everyone who can see it.

A **notification** is a fact about one person: their leave was approved, their
punch is missing. It is generated by the system, never typed, and belongs to
exactly one user.

They are separate tables because they have nothing in common beyond appearing in
the same part of the interface. Collapsing them would mean a nullable employee
column and a nullable author column on one table, and every query filtering on
which kind it was.

Delivery is in-app only
-----------------------
The brief requires that paid email and SMS services are not mandatory, so the
notification centre is the one channel the system depends on. ``channel`` and the
delivery columns exist so an optional email adapter can record what it sent
without changing this schema, but nothing here requires an external service to
work.

Idempotency
-----------
``notifications.dedupe_key`` is unique. A job that re-runs - the missing-punch
sweep, an accrual notice - computes the same key and inserts nothing, rather than
telling someone the same thing five times. That is the difference between a
notification centre people read and one they learn to ignore.
"""

from __future__ import annotations

from datetime import date, datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    Boolean,
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import ActorMixin, Base, Jsonb, PrimaryKey, TimestampMixin

#: Who an announcement is aimed at.
TARGET_TYPES = ("all", "department", "work_location", "employee_group", "employee")

#: Announcement lifecycle. ``scheduled`` becomes ``published`` when its
#: ``publish_at`` passes - by the job, or lazily on read.
ANNOUNCEMENT_STATUSES = ("draft", "scheduled", "published", "expired", "withdrawn")

#: Importance. ``critical`` is for something people must not miss, such as an
#: unplanned office closure; it is shown differently and cannot be dismissed
#: without being opened.
PRIORITIES = ("normal", "important", "critical")

#: What a notification is about. Used for grouping and filtering, and for an
#: employee to mute a category later without losing the record.
NOTIFICATION_CATEGORIES = (
    "leave",
    "compoff",
    "attendance",
    "regularization",
    "shift",
    "holiday",
    "payroll",
    "announcement",
    "account",
    "system",
)

#: Delivery channel. Only ``in_app`` is guaranteed; the others exist so an
#: optional adapter can record an attempt without a schema change.
CHANNELS = ("in_app", "email", "sms", "push")

DELIVERY_STATUSES = ("pending", "sent", "failed", "skipped")


class Announcement(Base, TimestampMixin, ActorMixin):
    """Something HR publishes for people to read."""

    __tablename__ = "announcements"
    __table_args__ = (
        CheckConstraint(f"status IN {ANNOUNCEMENT_STATUSES}", name="status_known"),
        CheckConstraint(f"priority IN {PRIORITIES}", name="priority_known"),
        CheckConstraint(
            "expires_at IS NULL OR publish_at IS NULL OR expires_at > publish_at",
            name="expiry_after_publish",
        ),
        Index("ix_announcements_status_publish", "status", "publish_at"),
        # Backs the employee-facing feed: a small slice of a table that grows
        # for the life of the company.
        Index(
            "ix_announcements_live",
            "publish_at",
            postgresql_where=text("status = 'published'"),
        ),
    )

    id: Mapped[PrimaryKey]
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    body: Mapped[str] = mapped_column(Text, nullable=False)
    """Plain text or Markdown. Rendered as text, never as HTML, so a pasted
    announcement cannot inject script into everyone's browser."""

    summary: Mapped[str | None] = mapped_column(String(300), nullable=True)
    """Optional one-line version for the list and the notification it generates."""

    priority: Mapped[str] = mapped_column(
        String(20), nullable=False, server_default=text("'normal'")
    )
    category: Mapped[str] = mapped_column(
        String(30), nullable=False, server_default=text("'announcement'")
    )

    status: Mapped[str] = mapped_column(String(20), nullable=False, server_default=text("'draft'"))

    publish_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    """
    When it becomes visible. Null on a draft. Scheduling is a stored instant
    rather than a job that must have run, so a missed job delays the
    notification but never hides the announcement itself.
    """

    expires_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    """Null never expires. An expired announcement is hidden, not deleted."""

    published_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    withdrawn_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    withdrawal_reason: Mapped[str | None] = mapped_column(Text, nullable=True)

    pin_until: Mapped[date | None] = mapped_column(Date, nullable=True)
    """Keeps it at the top of the feed until this date."""

    notify_on_publish: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=text("true")
    )
    """
    Whether publishing also puts a notification in each recipient's centre.
    Off for something low-value, so the centre stays worth reading.
    """

    notifications_sent_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
    """Set once the fan-out has run, so a republish cannot notify twice."""

    recipient_count: Mapped[int | None] = mapped_column(Integer, nullable=True)
    """How many people it reached, recorded at publication for the record."""

    attachment_file_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("stored_files.id", ondelete="SET NULL"), nullable=True
    )
    image_file_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("stored_files.id", ondelete="SET NULL"), nullable=True
    )

    targets: Mapped[list[AnnouncementTarget]] = relationship(
        back_populates="announcement", cascade="all, delete-orphan"
    )
    reads: Mapped[list[AnnouncementRead]] = relationship(
        back_populates="announcement", cascade="all, delete-orphan"
    )

    @property
    def is_live(self) -> bool:
        return self.status == "published"

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Announcement {self.id} {self.title!r}>"


class AnnouncementTarget(Base):
    """Who an announcement is aimed at.

    Rows rather than a single scope column, because an announcement legitimately
    goes to several groups at once - two offices, or a department plus a named
    individual. The union of the rows is the audience.
    """

    __tablename__ = "announcement_targets"
    __table_args__ = (
        CheckConstraint(f"target_type IN {TARGET_TYPES}", name="target_type_known"),
        CheckConstraint(
            "(target_type = 'all' AND target_id IS NULL) "
            "OR (target_type <> 'all' AND target_id IS NOT NULL)",
            name="target_id_matches_type",
        ),
        UniqueConstraint("announcement_id", "target_type", "target_id"),
        Index("ix_announcement_targets_lookup", "target_type", "target_id"),
    )

    id: Mapped[PrimaryKey]
    announcement_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("announcements.id", ondelete="CASCADE"), nullable=False
    )
    target_type: Mapped[str] = mapped_column(String(30), nullable=False)
    target_id: Mapped[int | None] = mapped_column(BigInteger, nullable=True)
    """
    The department, location, group or employee id. Null only for ``all``.

    Deliberately **not** a foreign key: it points at one of four different
    tables depending on ``target_type``, and a polymorphic reference cannot be
    constrained. The service validates the id against the right table on write.
    """

    announcement: Mapped[Announcement] = relationship(back_populates="targets")


class AnnouncementRead(Base):
    """That one employee has opened one announcement.

    A row per read rather than a flag on the announcement, because "who has seen
    the closure notice" is a real question - especially for a critical one.
    """

    __tablename__ = "announcement_reads"
    __table_args__ = (
        UniqueConstraint("announcement_id", "employee_id"),
        Index("ix_announcement_reads_employee", "employee_id"),
    )

    id: Mapped[PrimaryKey]
    announcement_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("announcements.id", ondelete="CASCADE"), nullable=False
    )
    employee_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("employees.id", ondelete="CASCADE"), nullable=False
    )
    read_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=text("now()")
    )
    acknowledged_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    """
    Set when an employee explicitly confirms a critical announcement. Distinct
    from reading it: opening a notice is not the same as confirming you have
    understood an office closure.
    """

    announcement: Mapped[Announcement] = relationship(back_populates="reads")


class Notification(Base):
    """One fact delivered to one user.

    ``dedupe_key`` is unique, which is what makes every notifying job safe to
    re-run. A missing-punch sweep that runs hourly must not tell someone about
    the same missing punch every hour.
    """

    __tablename__ = "notifications"
    __table_args__ = (
        CheckConstraint(f"category IN {NOTIFICATION_CATEGORIES}", name="category_known"),
        CheckConstraint(f"priority IN {PRIORITIES}", name="priority_known"),
        UniqueConstraint("dedupe_key"),
        # The unread badge and the centre itself, both scoped to one user.
        Index("ix_notifications_user_created", "user_id", "created_at"),
        Index(
            "ix_notifications_unread",
            "user_id",
            "created_at",
            postgresql_where=text("read_at IS NULL"),
        ),
        {"comment": "One fact per user. dedupe_key unique so a retried job cannot repeat."},
    )

    id: Mapped[PrimaryKey]
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    employee_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("employees.id", ondelete="SET NULL"), nullable=True
    )
    """
    Recorded alongside the user for reporting. The **user** is who receives it,
    because that is who signs in; an account without an employee record can still
    be notified about their account.
    """

    category: Mapped[str] = mapped_column(String(30), nullable=False)
    priority: Mapped[str] = mapped_column(
        String(20), nullable=False, server_default=text("'normal'")
    )

    title: Mapped[str] = mapped_column(String(200), nullable=False)
    body: Mapped[str | None] = mapped_column(Text, nullable=True)

    link_path: Mapped[str | None] = mapped_column(String(300), nullable=True)
    """
    Where to go when it is clicked, as an application path such as
    ``/leave``. A path rather than a URL so it cannot be used to send someone
    off-site, and so it keeps working if the deployment moves.
    """

    entity_type: Mapped[str | None] = mapped_column(String(50), nullable=True)
    entity_id: Mapped[str | None] = mapped_column(String(50), nullable=True)

    dedupe_key: Mapped[str] = mapped_column(String(200), nullable=False)
    """
    Deterministic per logical fact, e.g.
    ``leave.approved:application:42:user:7``. Excludes the time it was created,
    which would otherwise differ between runs and defeat the whole point.
    """

    read_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    archived_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)
    """Dismissed from the centre but kept, so the record of having been told stays."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, server_default=text("now()")
    )

    channel: Mapped[str] = mapped_column(
        String(20), nullable=False, server_default=text("'in_app'")
    )
    delivery_status: Mapped[str] = mapped_column(
        String(20), nullable=False, server_default=text("'sent'")
    )
    """
    In-app notifications are ``sent`` the moment the row exists - the centre is
    the delivery. The column is here so an optional email adapter can record
    ``pending`` and ``failed`` without a schema change, and without the in-app
    channel depending on it.
    """

    delivery_error: Mapped[str | None] = mapped_column(Text, nullable=True)
    payload: Mapped[dict[str, Any] | None] = mapped_column(Jsonb, nullable=True)

    job_run_id: Mapped[int | None] = mapped_column(
        BigInteger, ForeignKey("job_runs.id", ondelete="SET NULL"), nullable=True
    )

    @property
    def is_unread(self) -> bool:
        return self.read_at is None

    def __repr__(self) -> str:  # pragma: no cover - debugging aid
        return f"<Notification {self.category} user={self.user_id} {self.title!r}>"


class NotificationPreference(Base, TimestampMixin):
    """One user's choice to mute a category.

    A row only when muted, so the absence of a row means "notify me" - the
    default is to tell people things, and silence is the explicit choice.
    """

    __tablename__ = "notification_preferences"
    __table_args__ = (
        CheckConstraint(f"category IN {NOTIFICATION_CATEGORIES}", name="category_known"),
        CheckConstraint(f"channel IN {CHANNELS}", name="channel_known"),
        UniqueConstraint("user_id", "category", "channel"),
    )

    id: Mapped[PrimaryKey]
    user_id: Mapped[int] = mapped_column(
        BigInteger, ForeignKey("users.id", ondelete="CASCADE"), nullable=False
    )
    category: Mapped[str] = mapped_column(String(30), nullable=False)
    channel: Mapped[str] = mapped_column(
        String(20), nullable=False, server_default=text("'in_app'")
    )
    muted: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("false"))

    @property
    def is_muted(self) -> bool:
        return self.muted
